"""LaTeX table + macro generation (booktabs, IEEE/Elsevier friendly; mean ± SD across folds)."""
from __future__ import annotations

import re
from typing import Dict, List, Optional, Sequence

import numpy as np

from ..config import CLASS_NAMES, DISPLAY_NAMES as CLASS_DISPLAY

PENDING = r"\textemdash"


def disp(c: str) -> str:
    return CLASS_DISPLAY.get(c, c)


def pm(mean: Optional[float], sd: Optional[float], digits: int = 2, bold: bool = False) -> str:
    if mean is None or (isinstance(mean, float) and np.isnan(mean)):
        return PENDING
    s = f"{mean:.{digits}f} $\\pm$ {sd:.{digits}f}"
    return f"\\textbf{{{s}}}" if bold else s


def ms(values: Sequence[float]) -> tuple:
    v = np.asarray(values, dtype=float)
    return float(v.mean()), float(v.std(ddof=1)) if len(v) > 1 else 0.0


def esc(s: str) -> str:
    return re.sub(r"([_&%#$])", r"\\\1", s)


# Readable names for the legacy run identifiers (same wording as the paper text).
DISPLAY_NAMES = {
    "MobileViT": "MobileViT-S",
    "MobileViT_Standalone": "MobileViT-S",
    "EfficientNetB0": "EfficientNet-B0",
    "EffNet_MobileViT_Sequential": "EffNet-B0$\\rightarrow$MobileViT",
    "EffNet_MobileViT_ECA_Gated": "EffNet-B0+MobileViT (ECA)",
}


def model_name(s: str) -> str:
    return DISPLAY_NAMES.get(s, esc(s))


def _table(caption: str, label: str, colspec: str, header: str, rows: List[str], note: str = "",
           star: bool = False) -> str:
    """Springer Nature (sn-jnl) table style: caption+label first, full-width tabular*, \\botrule, footnotetext."""
    env = "table*" if star else "table"
    body = "\n".join(rows)
    note_tex = f"\\footnotetext{{{note}}}\n" if note else ""
    return (f"% AUTO-GENERATED by src/utils/overleaf_sync.py -- do not edit by hand\n"
            f"\\begin{{{env}}}[h]\n\\footnotesize\\setlength{{\\tabcolsep}}{{3pt}}%\n\\caption{{{caption}}}\\label{{{label}}}%\n"
            f"\\begin{{tabular*}}{{\\textwidth}}{{@{{\\extracolsep\\fill}}{colspec}@{{}}}}\n\\toprule\n{header} \\\\\n\\midrule\n"
            f"{body}\n\\botrule\n\\end{{tabular*}}\n{note_tex}\\end{{{env}}}\n")


# ----------------------------------------------------------------------------- legacy tables
def legacy_cv_table(s: Dict) -> str:
    rows = []
    for proto, tag in (("random_split_cv", "Random (leaky)"), ("group_aware_cv", "Group-aware")):
        for model, v in s.get(proto, {}).items():
            a, f, m = ms(v["accuracy"]), ms(v["macro_f1"]), ms(v["mcc"])
            rows.append(f"{model_name(model)} & {tag} & 224 & {pm(*a)} & {pm(*f)} & {pm(*m, digits=3)} \\\\")
    return _table("Historical 5-fold CV results recovered from the legacy Kaggle archives. "
                  "Random splits ignore duplicate groups and are therefore optimistically biased.",
                  "tab:legacy_cv", "llcccc",
                  "Model & Split protocol & Res. & Accuracy (\\%) & Macro-F1 (\\%) & MCC", rows)


def policy_screen_table(s: Dict) -> str:
    rows = []
    for r in s.get("policy_screen", []):
        rows.append(f"{esc(str(r['augmentation']))} & {esc(str(r['class_weight']))} & "
                    f"{r['screen_macro_f1']:.2f} & {r['screen_weighted_f1']:.2f} & "
                    f"{100 * r['screen_nematode_recall']:.1f} & {100 * r['screen_pest_recall']:.1f} \\\\")
    return _table("Legacy augmentation/class-weight screen (MobileViT-S, fold 1, 4 epochs).",
                  "tab:legacy_policy", "llcccc",
                  "Augmentation & Class weight & Macro-F1 & Weighted-F1 & Nematode rec. & Pest rec.", rows)


def data_audit_table(s: Dict, clean_counts: Optional[Dict[str, int]] = None) -> str:
    tot = s.get("class_totals", {})
    red = s.get("exact_duplicates", {}).get("redundant_copies_by_class", {})
    n = sum(tot.values()) or 1
    rows = []
    for c in CLASS_NAMES:
        clean = clean_counts.get(c) if clean_counts else None
        rows.append(f"{disp(c)} & {tot.get(c, 0)} & {100 * tot.get(c, 0) / n:.1f} & {red.get(c, 0)} & "
                    f"{clean if clean is not None else PENDING} \\\\")
    rows.append("\\midrule")
    rows.append(f"Total & {n} & 100.0 & {sum(red.values())} & "
                f"{sum(clean_counts.values()) if clean_counts else PENDING} \\\\")
    return _table("Class distribution, redundant byte-level copies and post-cleaning counts.",
                  "tab:data_audit", "lcccc", "Class & Images & Share (\\%) & Redundant copies & After cleaning", rows)


# ----------------------------------------------------------------------------- new results
def main_comparison_table(entries: List[Dict]) -> str:
    """entries: {label, protocol, res, params, summary(cv_summary.json) | legacy lists}"""
    best_f1 = max((e["f1"][0] for e in entries if e.get("f1")), default=None)
    rows = []
    for e in entries:
        f1 = e.get("f1")
        bold = f1 is not None and best_f1 is not None and abs(f1[0] - best_f1) < 1e-9
        rows.append(f"{e['label']} & {e.get('res', '')} & {e.get('params', PENDING)} & "
                    f"{pm(*e['acc']) if e.get('acc') else PENDING} & "
                    f"{pm(*f1, bold=bold) if f1 else PENDING} & "
                    f"{pm(*e['mcc'], digits=3) if e.get('mcc') else PENDING} \\\\")
    return _table("Comparison with the legacy models under the same group-aware stratified 5-fold "
                  "protocol (mean $\\pm$ SD over five folds). Best Macro-F1 in bold.",
                  "tab:main_results", "lccccc",
                  "Model & Res. (px) & Params (M) & Accuracy (\\%) & Macro-F1 (\\%) & MCC", rows,
                  note="$^{\\dagger}$Legacy model from the earlier campaign, re-evaluated on the "
                       "group-aware folds. Res.: input resolution of each expert.")


def per_class_table(columns: List[Dict]) -> str:
    """columns: {label, per_class: {cls: (mean, sd)}}, F1 in %. Best value per class in bold.
    With exactly two columns a Delta column (second minus first, pp) is appended."""
    delta = len(columns) == 2
    header = "Class & " + " & ".join(c["label"] for c in columns) + (" & $\\Delta$ (pp)" if delta else "")
    rows = []
    for cls in CLASS_NAMES:
        vals = [c["per_class"].get(cls) for c in columns]
        best = max((v[0] for v in vals if v), default=None)
        cells = [pm(100 * v[0], 100 * v[1], digits=1, bold=(len(vals) > 1 and v[0] == best)) if v else PENDING
                 for v in vals]
        if delta:
            cells.append(f"{100 * (vals[1][0] - vals[0][0]):+.1f}" if all(vals) else PENDING)
        rows.append(f"{disp(cls)} & " + " & ".join(cells) + " \\\\")
    note = ("$^{\\dagger}$Strongest legacy model on the same group-aware folds. "
            "$\\Delta$: ASMOE V2 minus MobileViT-S.") if delta else ""
    return _table("Per-class F1 (\\%, mean $\\pm$ SD over five folds). Best value per class in bold.",
                  "tab:per_class", "l" + "c" * (len(columns) + delta), header, rows, note=note)


def ablation_table(entries: List[Dict], ref_f1: Optional[float]) -> str:
    rows = []
    for e in entries:
        f1 = e.get("f1")
        delta = f"{f1[0] - ref_f1:+.2f}" if (f1 and ref_f1 is not None) else PENDING
        nem = e.get("nematode_f1")
        rows.append(f"{e['label']} & {pm(*e['acc']) if e.get('acc') else PENDING} & "
                    f"{pm(*f1) if f1 else PENDING} & {delta} & "
                    f"{pm(100 * nem[0], 100 * nem[1], 1) if nem else PENDING} \\\\")
    return _table("Ablation study (each row removes or alters one component of the full ASMOE V2).",
                  "tab:ablation", "lcccc",
                  "Variant & Accuracy (\\%) & Macro-F1 (\\%) & $\\Delta$F1 & Nematode F1 (\\%)", rows)


# ----------------------------------------------------------------------------- macros
def _macro_name(s: str) -> str:
    digits = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five",
              "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}
    return "".join(digits.get(ch, ch) for ch in re.sub(r"[^A-Za-z0-9]", "", s))


def macros(values: Dict[str, Optional[str]]) -> str:
    lines = ["% AUTO-GENERATED by src/utils/overleaf_sync.py -- numbers used in the prose"]
    for k, v in values.items():
        name = _macro_name(k)
        lines.append(f"\\providecommand{{\\{name}}}{{}}\\renewcommand{{\\{name}}}{{{v if v is not None else PENDING}}}")
    return "\n".join(lines) + "\n"
